bool validate(uintptr_t base,uintptr_t& pool) {
    profile=nullptr;
    IMAGE_DOS_HEADER dos{}; IMAGE_NT_HEADERS32 nt{};
    if(!base || !read(base,dos) || dos.e_magic!=IMAGE_DOS_SIGNATURE || dos.e_lfanew<=0 || dos.e_lfanew>=0x1000 ||
       !read(base+dos.e_lfanew,nt) || nt.Signature!=IMAGE_NT_SIGNATURE || nt.FileHeader.Machine!=IMAGE_FILE_MACHINE_I386) return false;
    for(const auto& p:profiles) if(p.timestamp==nt.FileHeader.TimeDateStamp && p.size==nt.OptionalHeader.SizeOfImage) profile=&p;
    if(!profile) return false;
    for(const auto& site:nativeSites) {
        uint8_t actual[6]{};
        if(!read(base+site.rva+profile->policyDelta,actual,site.size) || std::memcmp(actual,site.bytes,site.size)) return false;
    }
    // The full continuation stores EAX, initializes a float, then pops and returns.
    // No flags returned by playback are consumed. Reject old sanitizer bridges.
    const uint8_t continuation[]={0x89,0x86,0xE0,1,0,0,0xC7,0x86,0xE4,1,0,0,0,0,0x40,0x40,0x5F,0x5E,0x5B,0xC2,8,0};
    uint8_t actual[sizeof(continuation)]{};
    if(!read(base+0x36404,actual) || std::memcmp(actual,continuation,sizeof(actual))) return false;
    uint32_t count=0;
    return read(base+profile->pool,pool) && pool>=0x10000 && read(pool-4,count) && count==20;
}
